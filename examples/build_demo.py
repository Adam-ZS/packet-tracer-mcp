"""Build a neutral practice LAN through a real MCP stdio client session.

Requires Packet Tracer and the installed upstream Control Center extension.
No screenshots are generated by this script. Open the live device windows and
capture actual results with pt_capture after verifying them.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client


async def build(output: str) -> None:
    parameters = StdioServerParameters(
        command=sys.executable,
        args=["-m", "packettracer_evidence_mcp.cli", "serve"],
        env=dict(os.environ),
    )
    async with (
        stdio_client(parameters) as (reader, writer),
        ClientSession(reader, writer) as session,
    ):
        await session.initialize()

        async def call(tool_name, **arguments):
            result = await session.call_tool(tool_name, arguments)
            if result.isError:
                raise RuntimeError(f"{tool_name}: {result.content}")
            value = result.structuredContent
            if value is None:
                value = json.loads(result.content[0].text)
            print(tool_name, json.dumps(value), flush=True)
            return value

        status = await call("pt_status")
        if not status["extension_alive"]:
            raise RuntimeError("Control Center is not responding. Run pt-evidence doctor --live.")
        await call("pt_new_project", confirm_discard=True)
        await call(
            "pt_project_info",
            name="Packet Tracer Evidence MCP",
            description="Public practice LAN using documentation addresses",
            additional_info="Neutral demo. No personal accounts or course content.",
        )
        for name, model, x, y in [
            ("R-DEMO", "2911", 280, 120),
            ("SW-DEMO", "2960-24TT", 560, 240),
            ("PC-DEMO", "PC-PT", 900, 350),
        ]:
            await call("pt_add_device", name=name, model=model, x=x, y=y)
        await call("pt_devices")
        await call(
            "pt_connect",
            a="R-DEMO",
            a_port="GigabitEthernet0/0",
            b="SW-DEMO",
            b_port="FastEthernet0/1",
        )
        await call(
            "pt_connect",
            a="PC-DEMO",
            a_port="FastEthernet0",
            b="SW-DEMO",
            b_port="FastEthernet0/2",
        )
        await call(
            "pt_pc_ip",
            device="PC-DEMO",
            address="192.0.2.2",
            mask="255.255.255.0",
            gateway="192.0.2.1",
        )
        result = await call(
            "pt_configure_ios",
            device="R-DEMO",
            config="\n".join(
                [
                    "enable",
                    "configure terminal",
                    "hostname R-DEMO",
                    "no ip domain-lookup",
                    "interface g0/0",
                    "ip address 192.0.2.1 255.255.255.0",
                    "no shutdown",
                    "end",
                    "write memory",
                ]
            ),
        )
        if result["detected_errors"]:
            raise RuntimeError("IOS reported errors; inspect the live console before continuing.")
        for text, x, y in [
            ("Packet Tracer Evidence MCP\nPublic practice LAN", 360, 35),
            ("R-DEMO G0/0\n192.0.2.1/24", 310, 130),
            ("SW-DEMO\nF0/1 router | F0/2 PC", 590, 225),
            ("PC-DEMO\n192.0.2.2/24 | GW 192.0.2.1", 930, 335),
        ]:
            await call("pt_add_note", text=text, x=x, y=y)
        await call("pt_center_canvas", x=570, y=220)
        await call("pt_save_project", path=output)
        print("Built and saved. Next: inspect interface status, verify a PC ping, then capture.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--discard-current", action="store_true", required=True)
    parser.add_argument("--output", default="demo.pkt", help="New workspace-relative output path")
    args = parser.parse_args()
    asyncio.run(build(args.output))


if __name__ == "__main__":
    main()
